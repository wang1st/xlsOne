def load_catalog(path: Path) -> dict[str, str]:
    catalog: dict[str, str] = {}
    for message in ET.parse(path).getroot().iter("message"):
        source = message.findtext("source")
        translation = message.find("translation")
        if (
            not source
            or translation is None
            or translation.get("type") in {"obsolete", "vanished", "unfinished"}
            or not translation.text
        ):
            continue
        catalog[source] = translation.text
    return catalog


def c_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def main() -> None:
    lines = [
        "/* Generated by scripts/generate_c_i18n.py; do not edit manually. */",
        "",
    ]
    for locale, path in LOCALES.items():
        catalog = load_catalog(path)
        catalog.update(OVERRIDES.get(locale, {}))
        lines.append(
            f"static const xls_i18n_entry xls_i18n_catalog_{locale}[] = {{"
        )
        for source in sorted(catalog, key=lambda value: value.encode("utf-8")):
            lines.append(
                f"    {{{c_string(source)}, {c_string(catalog[source])}}},"
            )
        lines.extend(["};", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
